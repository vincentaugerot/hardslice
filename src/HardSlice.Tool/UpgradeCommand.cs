using System.Text;
using System.Text.RegularExpressions;

namespace HardSlice.Tool;

// dotnet hardslice upgrade: brings a generated solution to the template of the version of the tool. It generates hardslice-api
// anew under the name of the solution and rewrites the files that the template owns from that generation. The files of the
// application are merged in three ways, from the generation that the solution records in .hardslice/generation/, as the template
// generated them the last time: one that the application did not change is updated, one that both changed is merged with git
// merge-file, its conflicts written between git markers. A file without a recorded generation, as in a solution generated before
// it was recorded, is never written over: it is listed with its diff, in the format of git, for a maintainer or the agent to
// merge. A file that the template may have moved is listed with its diff against its new path. Last, the generation of the
// template replaces .hardslice/generation/, the base of the next upgrade.
internal sealed class UpgradeCommand(ICommandRunner runner, ITemplateGenerator generator, TextWriter output, TextWriter error)
{
    // The upgrade wrote what it could, and conflicts or files of the application are left to merge, or HardSlice files are no
    // longer generated by it: the output lists them. 0 means that nothing is left, 1 that the upgrade failed, 2 a wrong command line.
    public const int MergeLeft = 3;

    // The rule sheets, which the template owns without protecting them.
    public const string RuleSheetsFolder = "docs/rules/";

    // The files of the application as the template generated them, written by dotnet new hardslice-api and by each upgrade, which
    // merges from them. Protected: no agent edits them, and no project compiles them.
    public const string GenerationFolder = ".hardslice/generation/";

    // The instruction files of the agents that the application owns. The generation leaves them out with the protected files, which
    // hold the skills and the hooks, so that no CLI reads an instruction twice: Gemini CLI reads GEMINI.md in every folder.
    // AGENTS.md stays, which every CLI reads only in the folder it runs in and its parents (docs/agents/support.md).
    public static readonly string[] AgentInstructionFiles = ["GEMINI.md", ".github/copilot-instructions.md"];

    // The files that dotnet new leaves out of a source by default, which an exclude list replaces.
    private static readonly string[] DefaultExclusions = ["**/[Bb]in/**", "**/[Oo]bj/**", ".template.config/**/*", "**/*.filelist", "**/*.user", "**/*.lock.json"];

    // The exclusions of the source of template.json that writes the generation into GenerationFolder, for the template of the given
    // name: the files that the template owns, and the instruction files of the agents. TemplatePackageTests compares them.
    public static IReadOnlyList<string> GenerationExclusions(string templateName) =>
        [.. DefaultExclusions, .. ProtectedFiles.Globs(templateName), $"{RuleSheetsFolder}**", .. AgentInstructionFiles];

    // The sample module, whose folders tell a solution generated with the sample.
    private static string[] SampleFolders(string name) => [$"src/{name}/Features/Bookings/", $"src/{name}.Domain/Bookings/"];

    // The changes that the upgrade accepts in the git tree: the update of the tool, which the upgrade needs first, changes its
    // manifest, and the generation writes it again at that same version.
    private static readonly string[] AcceptedChanges = [Solution.ToolManifest];

    public int Run(string currentDirectory, bool? sample)
    {
        var solution = Solution.Find(currentDirectory, error);
        if (solution is null || !CleanTree(solution) || Tracked(solution) is not { } tracked)
            return CheckCommand.Failure;

        var version = ToolVersion.Current;
        var (withSample, variant) = Variant(solution, sample);
        output.WriteLine($"==> Upgrading {solution.Name} to the template of dotnet hardslice {version}, {variant}");
        var work = Directory.CreateTempSubdirectory("hardslice-upgrade-");
        try
        {
            var target = Path.Combine(work.FullName, solution.Name);
            output.WriteLine($"==> Generating hardslice-api {version} as {solution.Name}{(withSample ? "" : " with --no-sample")}, in a temporary folder");
            if (!generator.Generate(solution, version, withSample, work.FullName, target, error))
                return CheckCommand.Failure;

            return Apply(solution, target, Path.Combine(work.FullName, "merge"), tracked, version);
        }
        finally
        {
            try
            {
                work.Delete(recursive: true);
            }
            catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
            {
                error.WriteLine($"warning: the temporary folder '{work.FullName}' could not be deleted: {exception.Message}");
            }
        }
    }

    // Whether the template owns the file: the protected files, which hold the rules and the agent kit, and the rule sheets. Every
    // other file of the template is a file of the application, generated once and then changed by it.
    public static bool OwnedByTemplate(string relativePath, string solutionName) =>
        ProtectedFiles.Match(relativePath, solutionName) is not null
        || relativePath.StartsWith(RuleSheetsFolder, StringComparison.OrdinalIgnoreCase);

    private static bool InGeneration(string relativePath) => relativePath.StartsWith(GenerationFolder, StringComparison.OrdinalIgnoreCase);

    private int Apply(Solution solution, string target, string mergeFolder, IReadOnlySet<string> tracked, string version)
    {
        var all = Files(target);
        if (all.Length == 0)
        {
            error.WriteLine($"error: the generation of hardslice-api {version} holds no file. Nothing was written to the solution.");
            return CheckCommand.Failure;
        }

        var generated = all.Where(path => !InGeneration(path)).ToArray();
        var generatedPaths = generated.ToHashSet(StringComparer.OrdinalIgnoreCase);
        var newBase = Path.Combine(target, GenerationFolder);
        var oldBase = Path.Combine(solution.Root, GenerationFolder);
        var recorded = Files(oldBase);
        var baseVersion = GenerationVersion(solution);
        var plan = new Plan(version, baseVersion);
        foreach (var path in generated)
        {
            var file = Path.Combine(solution.Root, path);
            var generatedFile = Path.Combine(target, path);
            var owned = OwnedByTemplate(path, solution.Name);
            if (!owned && File.Exists(file))
                KeepUserSecretsId(file, generatedFile);
            var baseFile = Path.Combine(oldBase, path);
            if (owned || !File.Exists(baseFile))
            {
                // The files that the template owns, and a file of the application without a recorded generation: dotnet hardslice
                // upgrade before the generation was recorded (PB-086).
                if (!File.Exists(file))
                    plan.Write(plan.Added, path, File.ReadAllBytes(generatedFile));
                else if (!SameText(File.ReadAllBytes(file), File.ReadAllBytes(generatedFile)))
                {
                    if (owned)
                        plan.Write(plan.Rewritten, path, File.ReadAllBytes(generatedFile));
                    else
                        plan.ToMerge.Add(path);
                }

                continue;
            }

            var kept = KeptUserSecretsId(file);
            var template = Normalized(Text(generatedFile), kept);
            var @base = Normalized(Text(baseFile), kept);
            if (template == @base)
                continue;
            if (!File.Exists(file))
            {
                plan.DeletedChanged.Add(path);
                continue;
            }

            var current = Text(file);
            var solutionText = Normalized(current, kept);
            if (solutionText == @base)
                plan.Write(plan.Updated, path, File.ReadAllBytes(generatedFile));
            else if (solutionText != template && !Merge(path, current, solutionText, @base, template, mergeFolder, plan))
                return CheckCommand.Failure;
        }

        // A file of the recorded generation that the template no longer generates: deleted when the application never changed it.
        foreach (var path in recorded.Where(path => !generatedPaths.Contains(path) && !OwnedByTemplate(path, solution.Name)))
        {
            var file = Path.Combine(solution.Root, path);
            if (!File.Exists(file))
                continue;
            var kept = KeptUserSecretsId(file);
            if (Normalized(Text(file), kept) == Normalized(Text(Path.Combine(oldBase, path)), kept))
                plan.Delete(plan.Removed, path);
            else
                plan.NoLongerGenerated.Add(path);
        }

        // A HardSlice file that the solution tracks in a folder of the template and that the template no longer generates: an
        // older template generated it, or a maintainer added it. Only the second must stay.
        var folders = ProtectedFiles.Folders(solution.Name).Where(folder => folder != GenerationFolder).Append(RuleSheetsFolder).ToArray();
        var notGenerated = tracked
            .Where(path => folders.Any(folder => path.StartsWith(folder, StringComparison.OrdinalIgnoreCase)) && !generatedPaths.Contains(path))
            .Where(path => File.Exists(Path.Combine(solution.Root, path)))
            .Order(StringComparer.Ordinal)
            .ToArray();

        // A file of the solution with the name of a file the template adds elsewhere: the template probably moved it, as it moved
        // the HTTP answers from Shared/Behaviors to Shared/Http. Left in place, the old copy may clash with the new one, unless it
        // is the one the template generated, which is then deleted above.
        var moved = plan.Added
            .SelectMany(path => tracked
                .Where(old => Path.GetFileName(old).Equals(Path.GetFileName(path), StringComparison.OrdinalIgnoreCase)
                    && !generatedPaths.Contains(old) && !InGeneration(old) && !plan.Removed.Contains(old) && File.Exists(Path.Combine(solution.Root, old)))
                .Select(old => (Old: old, New: path)))
            .OrderBy(move => move.Old, StringComparer.Ordinal)
            .ThenBy(move => move.New, StringComparer.Ordinal)
            .ToArray();

        // The generation of the template replaces the recorded one, each project with the UserSecretsId of the solution.
        var generation = Files(newBase);
        var baseChanged = 0;
        foreach (var path in generation)
        {
            var file = Path.Combine(solution.Root, path);
            var generatedFile = Path.Combine(newBase, path);
            if (File.Exists(file))
                KeepUserSecretsId(file, generatedFile);
            var recordedFile = Path.Combine(oldBase, path);
            if (!File.Exists(recordedFile) || !File.ReadAllBytes(recordedFile).AsSpan().SequenceEqual(File.ReadAllBytes(generatedFile)))
            {
                plan.Write(null, GenerationFolder + path, File.ReadAllBytes(generatedFile));
                baseChanged++;
            }
        }

        var generationPaths = generation.ToHashSet(StringComparer.Ordinal);
        foreach (var path in recorded.Where(path => !generationPaths.Contains(path)))
        {
            plan.Delete(null, GenerationFolder + path);
            baseChanged++;
        }

        if (!Write(solution, plan))
            return CheckCommand.Failure;

        WriteList(plan.Rewritten, $"HardSlice files rewritten from the template ({plan.Rewritten.Count}). A change made to one of them in the solution is gone: 'git diff' shows it, for a maintainer to put back one that still applies");
        WriteList(plan.Added, $"Files added from the template ({plan.Added.Count})");
        WriteList(plan.Updated, $"Files of the application updated from the template, unchanged by the application ({plan.Updated.Count})");
        WriteList(plan.Merged, $"Files of the application merged with the template, without conflict ({plan.Merged.Count}). Review each one with 'git diff'");
        WriteList(plan.Removed, $"Files of the application removed, which the template no longer generates and the application did not change ({plan.Removed.Count})");
        WriteList([.. moved.Select(move => $"{move.Old} -> {move.New}")], $"Files of the solution that the template may have moved, left as is ({moved.Length}). Each one has the name of a file added from the template: merge what the application changed in it into the new file, then delete it. In the diffs below, '-' lines are in the file of the solution only, '+' lines in the new file of the template {version} only");
        foreach (var (old, path) in moved)
            DiffMoved(old, path, Path.Combine(solution.Root, old), Path.Combine(target, path));
        WriteList(notGenerated, $"HardSlice files that the template does not generate, left as is ({notGenerated.Length}). Delete each one that an older template generated, keep one that a maintainer added");
        WriteList(plan.NoLongerGenerated, $"Files of the application that the template no longer generates, changed by the application, left as is ({plan.NoLongerGenerated.Count}). Delete each one that the application no longer needs");
        WriteList(plan.DeletedChanged, $"Files that the application deleted and the template changed, left deleted ({plan.DeletedChanged.Count}). Restore one that the application needs from {GenerationFolder}, which holds the new generation");
        WriteList(plan.Conflicts, $"Conflicts to resolve ({plan.Conflicts.Count}). Each file holds both changes between git conflict markers: '<<<<<<< solution', then '||||||| {plan.BaseLabel}' before the lines as the template generated them, then '=======' before '>>>>>>> template {version}'. Keep what each side needs, then remove the markers");
        WriteList(plan.ToMerge, $"Files of the application that differ from the template, with no generation recorded in {GenerationFolder} to merge from, left as is ({plan.ToMerge.Count}). Merge into each one what the template changed, by hand or with the agent: in the diffs below, '-' lines are in the solution only, '+' lines in the template {version} only");
        foreach (var path in plan.ToMerge)
            Diff(path, Path.Combine(solution.Root, path), Path.Combine(target, path));
        if (baseChanged > 0)
            output.WriteLine(recorded.Length == 0
                ? $"==> The generation of the template is recorded in {GenerationFolder} ({generation.Length} files): the next upgrade merges the files of the application from it."
                : $"==> {GenerationFolder} now holds the generation of the template {version}, the base of the next upgrade.");

        var left = plan.ToMerge.Count + moved.Length + notGenerated.Length + plan.NoLongerGenerated.Count + plan.DeletedChanged.Count;
        var summary = $"{Count(plan.Rewritten.Count, "HardSlice file")} rewritten, {Count(plan.Added.Count, "file")} added, {plan.Updated.Count} updated, "
            + $"{plan.Merged.Count} merged, {plan.Removed.Count} removed, {Count(plan.Conflicts.Count, "conflict")} to resolve, {Count(left, "file")} left to merge or to review";
        if (left + plan.Conflicts.Count == 0)
        {
            output.WriteLine($"==> Upgrade done: {summary}. Review the changes with 'git diff', then run 'dotnet hardslice check'.");
            return 0;
        }

        var todo = (plan.Conflicts.Count, left) switch
        {
            ( > 0, > 0) => "Resolve the conflicts and merge the files listed above",
            ( > 0, _) => "Resolve the conflicts listed above",
            _ => "Merge the files listed above",
        };
        output.WriteLine($"==> Upgrade done: {summary}. {todo}, review the changes with 'git diff', then run 'dotnet hardslice check'.");
        return MergeLeft;
    }

    private static string Count(int count, string noun) => $"{count} {noun}{(count == 1 ? "" : "s")}";

    // The files under the folder, relative to it with '/', in order. None when it does not exist.
    private static string[] Files(string folder) =>
        Directory.Exists(folder)
            ? Directory.EnumerateFiles(folder, "*", SearchOption.AllDirectories)
                .Select(file => Path.GetRelativePath(folder, file).Replace('\\', '/'))
                .Order(StringComparer.Ordinal)
                .ToArray()
            : [];

    // What the upgrade writes, in order, with the lists it prints. A null content deletes the file.
    private sealed class Plan(string version, string baseVersion)
    {
        public string Version { get; } = version;
        // The label of the recorded generation in the conflict markers, with its version when the solution tells it.
        public string BaseLabel { get; } = $"generation {baseVersion}".TrimEnd();
        public List<(string Path, byte[]? Content)> Writes { get; } = [];
        public List<string> Rewritten { get; } = [];
        public List<string> Added { get; } = [];
        public List<string> Updated { get; } = [];
        public List<string> Merged { get; } = [];
        public List<string> Conflicts { get; } = [];
        public List<string> Removed { get; } = [];
        public List<string> NoLongerGenerated { get; } = [];
        public List<string> DeletedChanged { get; } = [];
        public List<string> ToMerge { get; } = [];

        public void Write(List<string>? list, string path, byte[] content)
        {
            list?.Add(path);
            Writes.Add((path, content));
        }

        public void Delete(List<string>? list, string path)
        {
            list?.Add(path);
            Writes.Add((path, null));
        }
    }

    // git merge-file, on the three normalized texts, written back with the line breaks and the mark of UTF-8 of the solution, the
    // original text of the file.
    private bool Merge(string path, string original, string solution, string @base, string template, string mergeFolder, Plan plan)
    {
        var folder = Path.Combine(mergeFolder, (plan.Merged.Count + plan.Conflicts.Count).ToString(System.Globalization.CultureInfo.InvariantCulture));
        Directory.CreateDirectory(folder);
        var current = Path.Combine(folder, "solution");
        var baseFile = Path.Combine(folder, "generation");
        var other = Path.Combine(folder, "template");
        var encoding = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false);
        File.WriteAllText(current, solution, encoding);
        File.WriteAllText(baseFile, @base, encoding);
        File.WriteAllText(other, template, encoding);
        string[] arguments = ["merge-file", "--diff3", "-L", "solution", "-L", plan.BaseLabel, "-L", $"template {plan.Version}", current, baseFile, other];
        var result = runner.Capture("git", arguments, mergeFolder);
        if (result.ExitCode is < 0 or > 127)
        {
            error.WriteLine($"error: 'git merge-file' exited with code {result.ExitCode} on {path}: {result.Error.Trim()}. Nothing was written.");
            return false;
        }

        var merged = Encoding.UTF8.GetString(File.ReadAllBytes(current));
        if (original.Contains("\r\n", StringComparison.Ordinal))
            merged = merged.Replace("\n", "\r\n", StringComparison.Ordinal);
        if (original.StartsWith('\uFEFF'))
            merged = '\uFEFF' + merged;
        plan.Write(result.ExitCode == 0 ? plan.Merged : plan.Conflicts, path, encoding.GetBytes(merged));
        return true;
    }

    // The version of HardSlice.Analyzers that the solution references, that of the template that generated it, read before the
    // upgrade rewrites it: the label of the recorded generation in the conflict markers. Empty when it cannot be read.
    private static string GenerationVersion(Solution solution)
    {
        var file = Path.Combine(solution.Root, AnalyzerVersion.ReferenceFile);
        if (!File.Exists(file))
            return "";
        var match = Regex.Match(Text(file), "Include=\"" + Regex.Escape(AnalyzerVersion.PackageId) + "\"\\s+Version=\"(?<version>[^\"]+)\"", RegexOptions.CultureInvariant);
        return match.Success ? match.Groups["version"].Value : "";
    }

    private bool Write(Solution solution, Plan plan)
    {
        var written = 0;
        try
        {
            foreach (var (path, content) in plan.Writes)
            {
                var file = Path.Combine(solution.Root, path);
                if (content is null)
                {
                    File.Delete(file);
                    DeleteEmptyFolders(solution.Root, Path.GetDirectoryName(file)!);
                }
                else
                {
                    Directory.CreateDirectory(Path.GetDirectoryName(file)!);
                    File.WriteAllBytes(file, content);
                }

                written++;
            }

            return true;
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            error.WriteLine(
                $"error: the upgrade stopped after writing {written} of {plan.Writes.Count} files, on {plan.Writes[written].Path}: {exception.Message}. "
                + "Run 'git status' to see what it wrote, and 'git checkout' and 'git clean' to bring the solution back.");
            return false;
        }
    }

    // git keeps no empty folder: neither does the upgrade, up to the root of the solution.
    private static void DeleteEmptyFolders(string root, string folder)
    {
        var rootPath = Path.GetFullPath(root).TrimEnd(Path.DirectorySeparatorChar);
        for (var current = Path.GetFullPath(folder); current.Length > rootPath.Length && Directory.Exists(current) && !Directory.EnumerateFileSystemEntries(current).Any(); current = Path.GetDirectoryName(current)!)
            Directory.Delete(current);
    }

    private void WriteList(IReadOnlyList<string> paths, string title)
    {
        if (paths.Count == 0)
            return;
        output.WriteLine($"==> {title}:");
        foreach (var path in paths)
            output.WriteLine($"    {path}");
    }

    // The diff of a file of the application without a recorded generation, from the solution to the template, with the headers of
    // git: cut out of the output, from its 'diff --git' line, it applies with git apply. Its title line ends the list above it.
    private void Diff(string path, string solutionFile, string templateFile)
    {
        output.WriteLine($"==> Diff of {path}");
        if (!UnifiedDiff.Write(output, path, path, Text(solutionFile), Text(templateFile)))
            output.WriteLine($"==> {path} differs from the template only by its line breaks.");
    }

    // The diff of a file that the template may have moved, from the old file of the solution to the new file of the template, and a
    // line when they differ only by their namespace declaration, as the HTTP answers moved from Shared/Behaviors to Shared/Http.
    private void DiffMoved(string old, string path, string solutionFile, string templateFile)
    {
        var before = Normalized(Text(solutionFile), null);
        var after = Normalized(Text(templateFile), null);
        output.WriteLine($"==> Diff of {old} against {path}");
        if (!UnifiedDiff.Write(output, old, path, before, after))
            output.WriteLine($"==> {old} is the same as {path}: nothing to merge, delete it.");
        else if (NamespaceDeclaration.Replace(before, "namespace;") == NamespaceDeclaration.Replace(after, "namespace;"))
            output.WriteLine($"==> {old} differs from {path} only by its namespace declaration: nothing to merge, delete it.");
    }

    // The declaration of a namespace on a line of its own, file-scoped or block-scoped.
    private static readonly Regex NamespaceDeclaration = new(@"^[ \t]*namespace[ \t]+[\w.]+[ \t]*;?[ \t]*$", RegexOptions.Multiline | RegexOptions.CultureInvariant);

    private static string Text(string file) => Encoding.UTF8.GetString(File.ReadAllBytes(file));

    private static readonly Regex UserSecretsId = new("<UserSecretsId>[^<]*</UserSecretsId>", RegexOptions.CultureInvariant);

    // dotnet new draws a new UserSecretsId at each generation: the generated project takes the one of the solution, so that it
    // differs from the project of the solution only by what the template changed, and is not listed at every upgrade.
    private static void KeepUserSecretsId(string solutionFile, string generatedFile)
    {
        if (!generatedFile.EndsWith(".csproj", StringComparison.OrdinalIgnoreCase))
            return;
        var kept = UserSecretsId.Match(Text(solutionFile));
        var generated = Text(generatedFile);
        if (kept.Success && UserSecretsId.IsMatch(generated))
            File.WriteAllText(generatedFile, UserSecretsId.Replace(generated, kept.Value.Replace("$", "$$", StringComparison.Ordinal), 1));
    }

    // The text with \n line breaks, without the mark of UTF-8, and with the UserSecretsId element that KeptUserSecretsId gives: the
    // texts of the solution, of the recorded generation and of the template compare and merge on what they say.
    private static string Normalized(string text, string? userSecretsId)
    {
        text = text.TrimStart('\uFEFF').Replace("\r\n", "\n", StringComparison.Ordinal);
        return userSecretsId is null ? text : UserSecretsId.Replace(text, userSecretsId.Replace("$", "$$", StringComparison.Ordinal), 1);
    }

    // For a project, the UserSecretsId element of the project of the solution, or an empty one when the solution has none: each
    // generation draws its own. Null for any other file.
    private static string? KeptUserSecretsId(string solutionFile)
    {
        if (!solutionFile.EndsWith(".csproj", StringComparison.OrdinalIgnoreCase))
            return null;
        var kept = File.Exists(solutionFile) ? UserSecretsId.Match(Text(solutionFile)) : Match.Empty;
        return kept.Success ? kept.Value : "<UserSecretsId></UserSecretsId>";
    }

    // The same bytes, or the same text once \r\n is read as \n: git may check files out with the line breaks of Windows.
    private static bool SameText(byte[] solution, byte[] template) =>
        solution.AsSpan().SequenceEqual(template)
        || Encoding.UTF8.GetString(solution).Replace("\r\n", "\n") == Encoding.UTF8.GetString(template).Replace("\r\n", "\n");

    // With --sample or --no-sample, as given. Otherwise the sample module tells: the template generates it with the sample only.
    private static (bool Sample, string Description) Variant(Solution solution, bool? sample)
    {
        if (sample is { } given)
            return (given, given ? "with the sample, as --sample asks" : "without the sample, as --no-sample asks");

        var folders = SampleFolders(solution.Name);
        var found = folders.FirstOrDefault(folder => Directory.Exists(Path.Combine(solution.Root, folder)));
        return found is null
            ? (false, $"without the sample, since the solution has no {string.Join(" nor ", folders)} (--sample to keep it)")
            : (true, $"with the sample, since the solution has {found} (--no-sample to leave it out)");
    }

    // The upgrade writes many files, protected ones among them: it starts from a git tree without changes, so that 'git diff' then
    // shows its changes alone, and 'git checkout' undoes them.
    private bool CleanTree(Solution solution)
    {
        var repository = runner.Capture("git", ["rev-parse", "--show-prefix"], solution.Root);
        if (repository.ExitCode != 0)
        {
            error.WriteLine(
                $"error: '{solution.Root}' is not in a git repository, or git cannot run ({repository.Error.Trim()}): dotnet hardslice upgrade "
                + "rewrites HardSlice files and needs git to show and undo its changes. Fix: commit the solution to a git repository, then run the upgrade again. "
                + "Nothing was written.");
            return false;
        }

        var status = Git(solution, "status", "--porcelain=v1", "-z", "--no-renames", "--untracked-files=all", "--", ".");
        if (status is null)
            return false;

        var folder = repository.Output.Trim();
        var changes = status.Split('\0', StringSplitOptions.RemoveEmptyEntries)
            .Where(record => record.Length > 3)
            .Select(record => record[3..])
            .Select(path => path.StartsWith(folder, StringComparison.Ordinal) ? path[folder.Length..] : path)
            .Where(path => !AcceptedChanges.Contains(path, StringComparer.OrdinalIgnoreCase))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToArray();
        if (changes.Length == 0)
            return true;

        error.WriteLine(
            $"error: the git tree of the solution has {changes.Length} {(changes.Length == 1 ? "change" : "changes")} not committed: "
            + $"{string.Join(", ", changes.Take(10))}{(changes.Length > 10 ? ", ..." : "")}. dotnet hardslice upgrade writes many files and starts "
            + $"from a tree without changes, so that 'git diff' shows its own alone. Fix: commit or stash them, then run the upgrade again. "
            + $"Only {string.Join(", ", AcceptedChanges)}, which the update of the tool changes, may be left. Nothing was written.");
        return false;
    }

    // The files that git tracks in the solution, relative to its root.
    private IReadOnlySet<string>? Tracked(Solution solution) =>
        Git(solution, "ls-files", "-z")?.Split('\0', StringSplitOptions.RemoveEmptyEntries).ToHashSet(StringComparer.Ordinal);

    private string? Git(Solution solution, params string[] arguments)
    {
        var result = runner.Capture("git", arguments, solution.Root);
        if (result.ExitCode == 0)
            return result.Output;

        error.WriteLine($"error: 'git {string.Join(' ', arguments)}' exited with code {result.ExitCode}: {result.Error.Trim()}. Nothing was written.");
        return null;
    }
}
