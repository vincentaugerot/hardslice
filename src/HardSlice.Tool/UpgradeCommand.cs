using System.Text;
using System.Text.RegularExpressions;

namespace HardSlice.Tool;

// dotnet hardslice upgrade: brings a generated solution to the template of the version of the tool. It generates hardslice-api
// anew under the name of the solution, rewrites the files that the template owns from that generation, adds the files the
// solution lacks, and lists, with their diff, the files of the application that differ from it, for a maintainer or the agent to
// merge. No generation of the version that generated the solution is restored: a change of the application cannot be told from a
// change of the template, so no file of the application is ever written over.
internal sealed class UpgradeCommand(ICommandRunner runner, ITemplateGenerator generator, TextWriter output, TextWriter error)
{
    // The upgrade wrote what it could, and files of the application differ from the template, or HardSlice files are no longer
    // generated by it: the output lists them. 0 means that nothing is left, 1 that the upgrade failed, 2 a wrong command line.
    public const int MergeLeft = 3;

    // The rule sheets, which the template owns without protecting them.
    public const string RuleSheetsFolder = "docs/rules/";

    // The sample module, whose folders tell a solution generated with the sample.
    private static string[] SampleFolders(string name) => [$"src/{name}/Features/Bookings/", $"src/{name}.Domain/Bookings/"];

    // The changes that the upgrade accepts in the git tree: the update of the tool, which the upgrade needs first, changes its
    // manifest, and the generation writes it again at that same version.
    private static readonly string[] AcceptedChanges = [Solution.ToolManifest];

    public int Run(string currentDirectory, bool? sample)
    {
        var solution = Solution.Find(currentDirectory, error);
        if (solution is null || !CleanTree(solution) || Tracked(solution) is not { } tracked)
            return CheckCommand.Failure;

        var version = ToolVersion.Current;
        var (withSample, variant) = Variant(solution, sample);
        output.WriteLine($"==> Upgrading {solution.Name} to the template of dotnet hardslice {version}, {variant}");
        var work = Directory.CreateTempSubdirectory("hardslice-upgrade-");
        try
        {
            var target = Path.Combine(work.FullName, solution.Name);
            output.WriteLine($"==> Generating hardslice-api {version} as {solution.Name}{(withSample ? "" : " with --no-sample")}, in a temporary folder");
            if (!generator.Generate(solution, version, withSample, work.FullName, target, error))
                return CheckCommand.Failure;

            return Apply(solution, target, tracked, version);
        }
        finally
        {
            try
            {
                work.Delete(recursive: true);
            }
            catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
            {
                error.WriteLine($"warning: the temporary folder '{work.FullName}' could not be deleted: {exception.Message}");
            }
        }
    }

    // Whether the template owns the file: the protected files, which hold the rules and the agent kit, and the rule sheets. Every
    // other file of the template is a file of the application, generated once and then changed by it.
    public static bool OwnedByTemplate(string relativePath, string solutionName) =>
        ProtectedFiles.Match(relativePath, solutionName) is not null
        || relativePath.StartsWith(RuleSheetsFolder, StringComparison.OrdinalIgnoreCase);

    private int Apply(Solution solution, string target, IReadOnlySet<string> tracked, string version)
    {
        var generated = Directory.EnumerateFiles(target, "*", SearchOption.AllDirectories)
            .Select(file => Path.GetRelativePath(target, file).Replace('\\', '/'))
            .Order(StringComparer.Ordinal)
            .ToArray();
        if (generated.Length == 0)
        {
            error.WriteLine($"error: the generation of hardslice-api {version} holds no file. Nothing was written to the solution.");
            return CheckCommand.Failure;
        }

        var rewritten = new List<string>();
        var added = new List<string>();
        var toMerge = new List<string>();
        var writes = new List<string>();
        foreach (var path in generated)
        {
            var file = Path.Combine(solution.Root, path);
            var owned = OwnedByTemplate(path, solution.Name);
            if (!owned && File.Exists(file))
                KeepUserSecretsId(file, Path.Combine(target, path));
            if (!File.Exists(file))
            {
                added.Add(path);
                writes.Add(path);
            }
            else if (!SameText(File.ReadAllBytes(file), File.ReadAllBytes(Path.Combine(target, path))))
            {
                (owned ? rewritten : toMerge).Add(path);
                if (owned)
                    writes.Add(path);
            }
        }

        // A HardSlice file that the solution tracks in a folder of the template and that the template no longer generates: an
        // older template generated it, or a maintainer added it. Only the second must stay.
        var generatedPaths = generated.ToHashSet(StringComparer.OrdinalIgnoreCase);
        var folders = ProtectedFiles.Folders(solution.Name).Append(RuleSheetsFolder).ToArray();
        var notGenerated = tracked
            .Where(path => folders.Any(folder => path.StartsWith(folder, StringComparison.OrdinalIgnoreCase)) && !generatedPaths.Contains(path))
            .Where(path => File.Exists(Path.Combine(solution.Root, path)))
            .Order(StringComparer.Ordinal)
            .ToArray();

        // A file of the solution with the name of a file the template adds elsewhere: the template probably moved it, as it moved
        // the HTTP answers from Shared/Behaviors to Shared/Http. Left in place, the old copy may clash with the new one.
        var moved = added
            .SelectMany(path => tracked
                .Where(old => Path.GetFileName(old).Equals(Path.GetFileName(path), StringComparison.OrdinalIgnoreCase)
                    && !generatedPaths.Contains(old) && File.Exists(Path.Combine(solution.Root, old)))
                .Select(old => $"{old} -> {path}"))
            .Order(StringComparer.Ordinal)
            .ToArray();

        var written = 0;
        try
        {
            foreach (var path in writes)
            {
                var file = Path.Combine(solution.Root, path);
                Directory.CreateDirectory(Path.GetDirectoryName(file)!);
                File.Copy(Path.Combine(target, path), file, overwrite: true);
                written++;
            }
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            error.WriteLine(
                $"error: the upgrade stopped after writing {written} of {writes.Count} files, on {writes[written]}: {exception.Message}. "
                + "Run 'git status' to see what it wrote, and 'git checkout' and 'git clean' to bring the solution back.");
            return CheckCommand.Failure;
        }

        WriteList(rewritten, $"HardSlice files rewritten from the template ({rewritten.Count}). A change made to one of them in the solution is gone: 'git diff' shows it, for a maintainer to put back one that still applies");
        WriteList(added, $"Files added from the template ({added.Count})");
        WriteList(moved, $"Files of the solution that the template may have moved, left as is ({moved.Length}). Each one has the name of a file added from the template: merge what the application changed in it into the new file, then delete it");
        WriteList(notGenerated, $"HardSlice files that the template does not generate, left as is ({notGenerated.Length}). Delete each one that an older template generated, keep one that a maintainer added");
        WriteList(toMerge, $"Files of the application that differ from the template, left as is ({toMerge.Count}). Merge into each one what the template changed, by hand or with the agent: in the diffs below, '-' lines are in the solution only, '+' lines in the template only");
        foreach (var path in toMerge)
            Diff(path, Path.Combine(solution.Root, path), Path.Combine(target, path), version);

        var left = toMerge.Count + moved.Length + notGenerated.Length;
        var summary = $"{rewritten.Count} HardSlice {(rewritten.Count == 1 ? "file" : "files")} rewritten, {added.Count} {(added.Count == 1 ? "file" : "files")} added";
        if (left == 0)
        {
            output.WriteLine($"==> Upgrade done: {summary}, nothing to merge. Review the changes with 'git diff', then run 'dotnet hardslice check'.");
            return 0;
        }

        output.WriteLine(
            $"==> Upgrade done, {left} {(left == 1 ? "file" : "files")} left to merge or to review: {summary}. "
            + "Merge the files listed above, review the changes with 'git diff', then run 'dotnet hardslice check'.");
        return MergeLeft;
    }

    private void WriteList(IReadOnlyList<string> paths, string title)
    {
        if (paths.Count == 0)
            return;
        output.WriteLine($"==> {title}:");
        foreach (var path in paths)
            output.WriteLine($"    {path}");
    }

    private void Diff(string path, string solutionFile, string templateFile, string version)
    {
        output.WriteLine($"==> Diff of {path}");
        output.WriteLine($"--- {path} (solution)");
        output.WriteLine($"+++ {path} (template {version})");
        var hunks = UnifiedDiff.Write(output, UnifiedDiff.Lines(Text(solutionFile)), UnifiedDiff.Lines(Text(templateFile)));
        if (hunks == 0)
            output.WriteLine("    Only the line break at the end of the file differs.");
    }

    private static string Text(string file) => Encoding.UTF8.GetString(File.ReadAllBytes(file));

    private static readonly Regex UserSecretsId = new("<UserSecretsId>[^<]*</UserSecretsId>", RegexOptions.CultureInvariant);

    // dotnet new draws a new UserSecretsId at each generation: the generated project takes the one of the solution, so that it
    // differs from the project of the solution only by what the template changed, and is not listed at every upgrade.
    private static void KeepUserSecretsId(string solutionFile, string generatedFile)
    {
        if (!generatedFile.EndsWith(".csproj", StringComparison.OrdinalIgnoreCase))
            return;
        var kept = UserSecretsId.Match(Text(solutionFile));
        var generated = Text(generatedFile);
        if (kept.Success && UserSecretsId.IsMatch(generated))
            File.WriteAllText(generatedFile, UserSecretsId.Replace(generated, kept.Value.Replace("$", "$$", StringComparison.Ordinal), 1));
    }

    // The same bytes, or the same text once \r\n is read as \n: git may check files out with the line breaks of Windows.
    private static bool SameText(byte[] solution, byte[] template) =>
        solution.AsSpan().SequenceEqual(template)
        || Encoding.UTF8.GetString(solution).Replace("\r\n", "\n") == Encoding.UTF8.GetString(template).Replace("\r\n", "\n");

    // With --sample or --no-sample, as given. Otherwise the sample module tells: the template generates it with the sample only.
    private static (bool Sample, string Description) Variant(Solution solution, bool? sample)
    {
        if (sample is { } given)
            return (given, given ? "with the sample, as --sample asks" : "without the sample, as --no-sample asks");

        var folders = SampleFolders(solution.Name);
        var found = folders.FirstOrDefault(folder => Directory.Exists(Path.Combine(solution.Root, folder)));
        return found is null
            ? (false, $"without the sample, since the solution has no {string.Join(" nor ", folders)} (--sample to keep it)")
            : (true, $"with the sample, since the solution has {found} (--no-sample to leave it out)");
    }

    // The upgrade writes many files, protected ones among them: it starts from a git tree without changes, so that 'git diff' then
    // shows its changes alone, and 'git checkout' undoes them.
    private bool CleanTree(Solution solution)
    {
        var repository = runner.Capture("git", ["rev-parse", "--show-prefix"], solution.Root);
        if (repository.ExitCode != 0)
        {
            error.WriteLine(
                $"error: '{solution.Root}' is not in a git repository, or git cannot run ({repository.Error.Trim()}): dotnet hardslice upgrade "
                + "rewrites HardSlice files and needs git to show and undo its changes. Fix: commit the solution to a git repository, then run the upgrade again. "
                + "Nothing was written.");
            return false;
        }

        var status = Git(solution, "status", "--porcelain=v1", "-z", "--no-renames", "--untracked-files=all", "--", ".");
        if (status is null)
            return false;

        var folder = repository.Output.Trim();
        var changes = status.Split('\0', StringSplitOptions.RemoveEmptyEntries)
            .Where(record => record.Length > 3)
            .Select(record => record[3..])
            .Select(path => path.StartsWith(folder, StringComparison.Ordinal) ? path[folder.Length..] : path)
            .Where(path => !AcceptedChanges.Contains(path, StringComparer.OrdinalIgnoreCase))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToArray();
        if (changes.Length == 0)
            return true;

        error.WriteLine(
            $"error: the git tree of the solution has {changes.Length} {(changes.Length == 1 ? "change" : "changes")} not committed: "
            + $"{string.Join(", ", changes.Take(10))}{(changes.Length > 10 ? ", ..." : "")}. dotnet hardslice upgrade writes many files and starts "
            + $"from a tree without changes, so that 'git diff' shows its own alone. Fix: commit or stash them, then run the upgrade again. "
            + $"Only {string.Join(", ", AcceptedChanges)}, which the update of the tool changes, may be left. Nothing was written.");
        return false;
    }

    // The files that git tracks in the solution, relative to its root.
    private IReadOnlySet<string>? Tracked(Solution solution) =>
        Git(solution, "ls-files", "-z")?.Split('\0', StringSplitOptions.RemoveEmptyEntries).ToHashSet(StringComparer.Ordinal);

    private string? Git(Solution solution, params string[] arguments)
    {
        var result = runner.Capture("git", arguments, solution.Root);
        if (result.ExitCode == 0)
            return result.Output;

        error.WriteLine($"error: 'git {string.Join(' ', arguments)}' exited with code {result.ExitCode}: {result.Error.Trim()}. Nothing was written.");
        return null;
    }
}
